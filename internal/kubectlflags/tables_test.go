const generated = "zz_generated.flags.go"

var update = flag.Bool("update", false, "rewrite "+generated+" from the pinned kubectl")

// TestTables regenerates the flag tables from the kubectl go.mod pins, and fails if zz_generated.flags.go differs.
//
// With -update, it rewrites the file instead, which is what kubectlflags.go's go:generate directive runs.
func TestTables(t *testing.T) {
	// kubectl adds or drops some flags by env var, e.g. KUBECTL_KUBERC=false drops --kuberc
	for _, kv := range os.Environ() {
		if name, _, _ := strings.Cut(kv, "="); strings.HasPrefix(name, "KUBECTL_") {
			t.Setenv(name, "")
		}
	}

	got, err := generate()
	require.NoError(t, err)
	if *update {
		require.NoError(t, os.WriteFile(generated, got, 0o644))
		return
	}
	want, err := os.ReadFile(generated)
	require.NoError(t, err)
	require.Equal(t, string(want), string(got), "%s is stale; run make gen", generated)
}

// commands are the kubectl commands kuba wraps, plus options for the global flags every command takes, as `kubectl
// options` lists them.
var commands = []string{"api-resources", "debug", "describe", "exec", "get", "logs", "options"}

// table is one command's flags, sorted by long name.
type table struct {
	command string
	flags   []Flag
}

// generate renders the Go source of the flag tables from kubectl's own command tree.
func generate() ([]byte, error) {
	root := kubectlCommand()
	var tables []table
	for _, command := range commands {
		fs, err := flagSet(root, command)
		if err != nil {
			return nil, err
		}
		flags, err := flagsOf(fs)
		if err != nil {
			return nil, fmt.Errorf("kubectl %s: %w", command, err)
		}
		tables = append(tables, table{command: command, flags: flags})
	}
	version, err := kubectlVersion()
	if err != nil {
		return nil, err
	}
	return render(version, tables)
}

// kubectlCommand builds kubectl's command tree as its main does, without running it.
//
// main's cli.RunNoErrOutput adds the logging flags, e.g. --v, after building the tree, so this adds them the same way.
//
// REF: https://github.com/kubernetes/kubernetes/blob/v1.37.1/cmd/kubectl/kubectl.go#L31-L44
// REF: https://github.com/kubernetes/component-base/blob/v0.37.1/cli/run.go#L116-L117
func kubectlCommand() *cobra.Command {
	root := kubectlcmd.NewKubectlCommand(kubectlcmd.KubectlOptions{IOStreams: genericiooptions.NewTestIOStreamsDiscard()})
	logs.AddFlags(root.PersistentFlags())
	return root
}

// flagSet is a command's own flags, or for options, the global flags every command takes.
func flagSet(root *cobra.Command, command string) (*pflag.FlagSet, error) {
	if command == "options" {
		return root.PersistentFlags(), nil
	}
	cmd, _, err := root.Find([]string{command})
	if err != nil {
		return nil, err
	}
	return cmd.LocalFlags(), nil
}

// flagsOf lists a flag set's flags, sorted by long name, where a flag is Bool iff its type is bool.
//
// It fails on a flag that takes an optional value, e.g. --dry-run, which alone means --dry-run=unchanged: Flag can't
// say so, and flagspec would take the word after it as its value.
func flagsOf(fs *pflag.FlagSet) ([]Flag, error) {
	var flags []Flag
	var errs []error
	fs.VisitAll(func(f *pflag.Flag) {
		isBool := f.Value.Type() == "bool"
		if f.NoOptDefVal != "" && !isBool {
			errs = append(errs, fmt.Errorf("--%s takes an optional value, which kubectlflags can't express", f.Name))
		}
		flags = append(flags, Flag{Long: f.Name, Short: f.Shorthand, Bool: isBool})
	})
	slices.SortFunc(flags, func(a, b Flag) int { return strings.Compare(a.Long, b.Long) })
	return flags, errors.Join(errs...)
}

// kubectlVersion is the version of the kubectl the test links, e.g. v1.37.1 for module k8s.io/kubectl v0.37.1.
//
// A release build stamps kubectl's version in, which a test build lacks. Its module version names the same release,
// tagged v0.X.Y for Kubernetes v1.X.Y.
func kubectlVersion() (string, error) {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return "", errors.New("no build info")
	}
	for _, dep := range info.Deps {
		if dep.Path != "k8s.io/kubectl" {
			continue
		}
		if minorPatch, ok := strings.CutPrefix(dep.Version, "v0."); ok {
			return "v1." + minorPatch, nil
		}
		return "", fmt.Errorf("k8s.io/kubectl %s: want a v0.X.Y version", dep.Version)
	}
	return "", errors.New("k8s.io/kubectl isn't in the build info")
}

// render writes the tables as gofmt'ed Go source.
func render(version string, tables []table) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	b.WriteString("package kubectlflags\n\n")
	fmt.Fprintf(&b, "// Version is the kubectl whose commands the tables come from.\nconst Version = %q\n\n", version)
	b.WriteString("// Commands lists each wrapped kubectl command's flags, by long name; options holds the global ones.\n")
	b.WriteString("var Commands = map[string][]Flag{\n")
	for _, t := range tables {
		fmt.Fprintf(&b, "\t%q: {\n", t.command)
		for _, f := range t.flags {
			fmt.Fprintf(&b, "\t\t{Long: %q, Short: %q, Bool: %t},\n", f.Long, f.Short, f.Bool)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
